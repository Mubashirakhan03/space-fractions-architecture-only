"""Write docs/MODEL_INPUT.md: exactly what the model receives in this architecture-only variant.

    python scripts/dump_model_input.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sfagent.agent import prompts  # noqa: E402
from sfagent.parsers.spec import build_spec  # noqa: E402


def main() -> int:
    spec = build_spec(ROOT / "samples" / "Architecture_Documentation.md", ROOT / "samples" / "Architecture_View.md")
    user = prompts.initial_messages(spec)[1]["content"]
    text = "\n".join([
        "# What the model receives (architecture-only variant)", "",
        "Generated by `scripts/dump_model_input.py`. Nothing else is sent: no task profile, no UI or feature rules,",
        "no analysis by the harness. Tool definitions (read/write/edit files, run compile/tests, todos, plan, finish)",
        "are sent as the API's tool list.", "",
        "## 1. System prompt — deviation switch OFF (baseline)", "", "```text", prompts.system_prompt(False), "```", "",
        "## 2. Added when the deviation switch is ON", "", "```text", prompts.DEVIATION_RULE,
        prompts.DEVIATION_OUTPUT, "```", "",
        "## 3. First user message (the architecture)", "",
        f"{len(user):,} characters: the deterministic extraction of the two architecture files (domain model from the",
        "UML views, requirements, document tables and the contracts/schemas). The original files are also copied to",
        "`agent_run/inputs/`. Removed compared with the earlier agent: `target_platform` (it contained the harness's",
        "own choice \"SQLite file\"), `input_issues`, `platform_conflicts`.", "",
        "```text", user[:1500] + "\n…", "```", "",
        "## 4. Phase instructions", "", "```text", prompts.plan_instructions(False), "", prompts.IMPLEMENT_INSTRUCTIONS,
        "```", "",
    ])
    out = ROOT / "docs" / "MODEL_INPUT.md"
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
